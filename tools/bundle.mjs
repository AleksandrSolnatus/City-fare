import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
let html=readFileSync(resolve(root,'dist/index.html'),'utf8');
const css=readFileSync(resolve(root,'dist/style.css'),'utf8');
const js=['aero.js','cactus-ledger.js','road.js','renderer.js','trip-save.js','game.js'].map(name=>readFileSync(resolve(root,'dist',name),'utf8').replace(/^import .*;\n/gm,'').replace(/^export /gm,'')).join('\n');
html=html.replace('<link rel="stylesheet" href="style.css">',()=>'<style>'+css+'</style>').replace('<script type="module" src="game.js"></script>',()=>'<script type="module">\n'+js+'\n</script>');
writeFileSync(resolve(root,'index.html'),html);
writeFileSync(resolve(root,'City-Fare-009.html'),html);
console.log('Built index.html and City-Fare-009.html ('+Buffer.byteLength(html)+' bytes)');
